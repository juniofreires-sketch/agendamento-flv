-- Portal FLV: esquema para um projeto Supabase novo.
-- Aplicar somente ao projeto dedicado ao portal.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 3 and 160)
);
create unique index if not exists suppliers_name_lower_unique on public.suppliers (lower(name));

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 120),
  email text not null,
  supplier_id bigint references public.suppliers(id),
  requested_supplier_name text check (requested_supplier_name is null or char_length(requested_supplier_name) between 3 and 160),
  role text not null default 'supplier' check (role in ('supplier','admin')),
  status text not null default 'pending' check (status in ('pending','active')),
  created_at timestamptz not null default now(),
  constraint supplier_profile_requires_supplier check (role = 'admin' or status = 'pending' or supplier_id is not null)
);
create index if not exists profiles_supplier_idx on public.profiles(supplier_id);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers(id),
  user_id uuid references auth.users(id) on delete set null,
  day date not null,
  slot time without time zone not null,
  order_number text check (char_length(order_number) <= 80),
  invoice_number text check (char_length(invoice_number) <= 80),
  weight_kg numeric(12,2) not null check (weight_kg > 0),
  item_count integer not null check (item_count >= 0),
  box_count integer not null check (box_count >= 0),
  vehicle_type text not null check (vehicle_type in ('3/4','BITREM','CARRETA 24','CARRETA 26','CARRETA 28','CARRETA 30','FIORINO','TOCO','TRUCK','VUC')),
  cargo_type text not null check (cargo_type in ('Batida / Paletizada','Carga batida','Paletizada','Pallet sobreposto')),
  status text not null default 'active' check (status in ('active','cancelled')),
  created_at timestamptz not null default now(),
  cancelled_at timestamptz
);
create index if not exists bookings_day_slot_idx on public.bookings(day,slot) where status='active';
create index if not exists bookings_supplier_day_idx on public.bookings(supplier_id,day desc);

alter table public.suppliers enable row level security;
alter table public.profiles enable row level security;
alter table public.bookings enable row level security;

create or replace function private.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin' and p.status = 'active'
  );
$$;

create or replace function private.current_supplier()
returns bigint language sql stable security definer set search_path = ''
as $$
  select p.supplier_id from public.profiles p
  where p.id = (select auth.uid()) and p.status = 'active'
  limit 1;
$$;

revoke all on function private.is_admin() from public, anon;
revoke all on function private.current_supplier() from public, anon;
grant execute on function private.is_admin() to authenticated;
grant execute on function private.current_supplier() to authenticated;

create policy suppliers_read on public.suppliers for select to anon, authenticated using (true);
create policy suppliers_admin_insert on public.suppliers for insert to authenticated
  with check ((select private.is_admin()));

create policy profiles_read on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select private.is_admin()));
create policy profiles_admin_approve on public.profiles for update to authenticated
  using (role='supplier' and (select private.is_admin()))
  with check (role='supplier' and (select private.is_admin()));

create policy bookings_read on public.bookings for select to authenticated
  using ((select private.is_admin()) or supplier_id = (select private.current_supplier()));
create policy bookings_insert on public.bookings for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and ((select private.is_admin()) or supplier_id = (select private.current_supplier()))
  );
create policy bookings_cancel on public.bookings for update to authenticated
  using (
    status='active'
    and ((select private.is_admin()) or supplier_id = (select private.current_supplier()))
  )
  with check (
    status='cancelled'
    and ((select private.is_admin()) or supplier_id = (select private.current_supplier()))
  );

create or replace function private.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  supplier_text text := new.raw_user_meta_data ->> 'supplier_id';
  selected_supplier bigint;
  requested_name text := nullif(trim(regexp_replace(coalesce(new.raw_user_meta_data ->> 'supplier_name', ''), '\s+', ' ', 'g')), '');
  display_name text := trim(coalesce(new.raw_user_meta_data ->> 'name', ''));
begin
  -- A conta administrativa so pode ser criada pela API administrativa do Supabase.
  -- app_metadata nao pode ser alterado por um cadastro publico.
  if lower(new.email) = 'junior.matheus64@gmail.com' then
    if coalesce(new.raw_app_meta_data ->> 'flv_admin_bootstrap', '') <> 'true' then
      raise exception 'O cadastro administrativo e feito pela equipe do portal.';
    end if;
    if char_length(display_name) < 2 or char_length(display_name) > 120 then
      raise exception 'Informe seu nome com 2 a 120 caracteres.';
    end if;
    insert into public.profiles(id,name,email,supplier_id,role,status)
    values(new.id,display_name,lower(new.email),null,'admin','active');
    return new;
  end if;
  if supplier_text ~ '^[0-9]+$' then selected_supplier := supplier_text::bigint; end if;
  if selected_supplier is not null and not exists (select 1 from public.suppliers where id=selected_supplier) then
    raise exception 'Selecione um fornecedor válido.';
  end if;
  if selected_supplier is null and (requested_name is null or char_length(requested_name) not between 3 and 160) then
    raise exception 'Selecione ou informe um fornecedor válido.';
  end if;
  if char_length(display_name) < 2 or char_length(display_name) > 120 then
    raise exception 'Informe seu nome com 2 a 120 caracteres.';
  end if;
  insert into public.profiles(id,name,email,supplier_id,requested_supplier_name,role,status)
  values(new.id,display_name,lower(new.email),selected_supplier,
    case when selected_supplier is null then requested_name else null end,'supplier','pending');
  return new;
end;
$$;
revoke all on function private.handle_new_user() from public, anon, authenticated;
create trigger on_flv_user_created
after insert on auth.users for each row execute function private.handle_new_user();

create or replace function private.assign_booking()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  requester public.profiles%rowtype;
  local_day date := (now() at time zone 'America/Sao_Paulo')::date;
  local_time time := (now() at time zone 'America/Sao_Paulo')::time;
  selected_slot time;
begin
  if (select auth.uid()) is null then raise exception 'Faça login para continuar.'; end if;
  select * into requester from public.profiles where id=(select auth.uid());
  if requester.id is null or requester.status <> 'active' then
    raise exception 'Seu cadastro precisa estar aprovado para agendar.';
  end if;
  if requester.role <> 'admin' then
    new.supplier_id := requester.supplier_id;
  end if;
  if new.supplier_id is null or not exists(select 1 from public.suppliers where id=new.supplier_id) then
    raise exception 'Selecione um fornecedor válido.';
  end if;
  if new.day < local_day or extract(dow from new.day)=0 then
    raise exception 'Agendamentos são feitos de segunda a sábado, das 05:00 às 10:00. Para entregas fora dessa janela, entre em contato com o setor comercial.';
  end if;

  -- Uma trava por dia evita que duas confirmações ocupem a sexta vaga da mesma faixa.
  perform pg_catalog.pg_advisory_xact_lock(414950, (new.day - date '2000-01-01')::integer);
  select c.slot into selected_slot
  from (
    select (time '05:00' + (n * interval '30 minutes'))::time as slot
    from pg_catalog.generate_series(0,10) as n
  ) c
  where (new.day > local_day or c.slot >= local_time)
    and (
      select count(*) from public.bookings b
      where b.day=new.day and b.slot=c.slot and b.status='active'
    ) < 5
  order by c.slot
  limit 1;
  if selected_slot is null then
    if new.day=local_day and local_time > time '10:00' then
      raise exception 'O horário de hoje terminou. Para entregas fora da janela, entre em contato com o setor comercial.';
    end if;
    raise exception 'Todos os horários desta data estão completos. Escolha outro dia ou entre em contato com o setor comercial.';
  end if;
  new.slot := selected_slot;
  new.user_id := (select auth.uid());
  new.status := 'active';
  new.cancelled_at := null;
  return new;
end;
$$;
revoke all on function private.assign_booking() from public, anon, authenticated;
create trigger assign_flv_booking
before insert on public.bookings for each row execute function private.assign_booking();

create or replace function private.cancel_booking_guard()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if old.user_id is not null and new.user_id is null
     and (to_jsonb(new) - 'user_id') = (to_jsonb(old) - 'user_id') then
    return new;
  end if;
  if old.status <> 'active' or new.status <> 'cancelled' then
    raise exception 'Este agendamento não pode ser cancelado.';
  end if;
  if (to_jsonb(new) - 'status' - 'cancelled_at') is distinct from
     (to_jsonb(old) - 'status' - 'cancelled_at') then
    raise exception 'Apenas o cancelamento é permitido.';
  end if;
  new.cancelled_at := now();
  return new;
end;
$$;
revoke all on function private.cancel_booking_guard() from public, anon, authenticated;
create trigger guard_flv_booking_cancel
before update on public.bookings for each row execute function private.cancel_booking_guard();

